// scripts/batch/templates/smartrecruiters.js
// Generator for a SmartRecruiters ATS source extractor.
//
// API: GET https://api.smartrecruiters.com/v1/companies/{slug}/postings
//   Returns { offset, limit, totalFound, content: [posting...] }
//   Posting shape: { id, name, company: {identifier, name},
//                    location: {city, region?, country, remote?},
//                    typeOfEmployment: {id, label},
//                    experienceLevel: {id, label},
//                    releasedDate, industry: {id, label},
//                    department: {id, label}, function: {id, label} }
//
// totalFound: 0 is a valid state -- meta.atsEmpty = true so verify passes.
// A future batch may hit sites with real postings; the extractor handles both.
//
// Public posting URL is CONSTRUCTED as
//   https://jobs.smartrecruiters.com/{slug}/{id}
// This is SmartRecruiters' standard public URL pattern but is NOT returned
// by the list API. If a link 404s, adjust buildPublicUrl() and re-verify.
//
// Uses plain fetch() -- no browser. The page argument is passed by the
// orchestrator but intentionally unused.

function q(s) {
    return String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function renderSmartRecruiters(name, slug) {
    if (!/^[a-z0-9_-]+$/.test(name)) throw new Error(`invalid source name: ${name}`);
    if (!slug) throw new Error('renderSmartRecruiters: slug is required');
    return `// Extractor: ${name} (jobs) -- SmartRecruiters ATS API.
// Generated by scripts/batch/templates/smartrecruiters.js. Hand-verify
// before commit; re-run \`pulchowk-events verify ${name}\` after any edit.
//
// Uses plain fetch() -- no browser. The page argument is passed by the
// orchestrator but intentionally unused.
//
// Empty postings list is a valid state (no open roles right now) --
// meta.atsEmpty is set true so verify passes rather than reporting drift.
//
// Public posting URLs are constructed as
//   https://jobs.smartrecruiters.com/{slug}/{id}
// The list API returns only the posting id, not the public URL.

const { safeDiscovered, safeUnitDone } = require('../../progress');
const { sanitizeJobFields } = require('../../jobs');

const SR_SLUG = '${q(slug)}';
const SR_API = \`https://api.smartrecruiters.com/v1/companies/\${SR_SLUG}/postings?limit=100\`;

function buildPublicUrl(id) {
    return 'https://jobs.smartrecruiters.com/' + SR_SLUG + '/' + id;
}

function buildLocation(loc) {
    if (!loc) return null;
    const parts = [loc.city, loc.region, loc.country].filter(Boolean);
    return parts.length ? parts.join(', ') : null;
}

function buildAttendance(loc) {
    if (!loc) return 'in-person';
    if (loc.remote === true) return 'remote';
    return 'in-person';
}

module.exports = {
    // browserless: true tells _orchestrate / verify-source / verify-worker
    // to skip Puppeteer entirely. This extractor uses fetch() only, so
    // launching Chromium is wasted work -- and worse, closeBrowser()
    // can hang 40s+ on an empty page, pinning the worker.
    browserless: true,
    async extract(page, { progress, meta }) {
        meta.pagesVisited++;
        const res = await fetch(SR_API, {
            headers: { 'User-Agent': 'Mozilla/5.0', 'Accept': 'application/json' },
            signal: AbortSignal.timeout(15000)
        });
        if (!res.ok) {
            throw new Error('smartrecruiters API HTTP ' + res.status);
        }
        const data = await res.json();
        const postings = Array.isArray(data.content) ? data.content : [];

        meta.listingHits = postings.length;
        safeDiscovered(progress, postings.length);

        if (postings.length === 0) {
            meta.atsEmpty = true;
            return { items: [], meta };
        }

        const items = [];
        for (const p of postings) {
            try {
                const companyName = (p.company && p.company.name) || '${q(name)}';
                const locationStr = buildLocation(p.location);
                const employmentType = (p.typeOfEmployment && p.typeOfEmployment.label) || null;
                const level = (p.experienceLevel && p.experienceLevel.label) || null;
                const department = (p.department && p.department.label) || null;
                const publicUrl = p.id ? buildPublicUrl(p.id) : null;

                const item = {
                    id: 'smartrecruiters-${q(slug)}-' + (p.id || p.name),
                    title: p.name || 'Untitled Job',
                    company: companyName,
                    companyUrl: null,
                    companyLogoUrl: null,
                    location: locationStr,
                    employmentType,
                    attendanceMode: buildAttendance(p.location),
                    salary: null,
                    experience: null,
                    level,
                    openings: null,
                    description: department ? ('Department: ' + department) : '',
                    responsibilities: '',
                    requirements: '',
                    skills: [],
                    companyDescription: '',
                    companyLocation: null,
                    companyAddress: null,
                    applicationEndsRaw: null,
                    applicationEndsDate: null,
                    daysLeftAtListTime: null,
                    url: publicUrl,
                    registrationUrl: publicUrl,
                    source: '${q(name)}',
                    scrapedAt: Date.now(),
                    publishedAt: p.releasedDate || null
                };

                sanitizeJobFields(item);
                if (item.title && item.url) {
                    items.push(item);
                } else {
                    meta.detailParseFailures++;
                }
            } catch (e) {
                meta.detailParseFailures++;
                console.warn('  [${q(name)}] smartrecruiters posting parse failed: ' + e.message);
            } finally {
                safeUnitDone(progress);
            }
        }

        return { items, meta };
    }
};
`;
}

module.exports = { renderSmartRecruiters };
