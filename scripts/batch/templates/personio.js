// scripts/batch/templates/personio.js
// Generator for a Personio ATS source extractor. Returns the full text of
// src/scrapers/extractors/jobs/<name>.js.
//
// Personio public XML feed: GET https://{slug}.jobs.personio.{tld}/xml?language=en
//   Returns <workzag-jobs><position>...</position>...</workzag-jobs>
//   Each <position> has id, subcompany, office, additionalOffices/office,
//   department, name (title), jobDescriptions/jobDescription (CDATA HTML
//   sections with <name> + <value>), employmentType, seniority, schedule,
//   yearsOfExperience, keywords (comma-sep), occupation, occupationCategory,
//   createdAt.
//
// Empty feed (<workzag-jobs> with zero <position>) is a valid state --
// meta.atsEmpty = true so verify passes rather than reporting drift.
//
// Public job URL is constructed as https://{slug}.jobs.personio.{tld}/job/{id}.
// This matches Personio's standard frontend URL pattern but is NOT validated
// by this generator. If a link 404s, adjust here and re-verify -- the item
// still posts, only the register-link click is affected.
//
// Uses plain fetch() -- no browser. The page argument is passed by the
// orchestrator but intentionally unused.

function q(s) {
    return String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function renderPersonio(name, slug, tld) {
    if (!/^[a-z0-9_-]+$/.test(name)) throw new Error(`invalid source name: ${name}`);
    if (!slug) throw new Error('renderPersonio: slug is required');
    if (!tld) throw new Error('renderPersonio: tld is required');
    return `// Extractor: ${name} (jobs) -- Personio ATS XML feed.
// Generated by scripts/batch/templates/personio.js. Hand-verify before commit;
// re-run \`pulchowk-events verify ${name}\` after any edit.
//
// Uses plain fetch() -- no browser. The page argument is passed by the
// orchestrator but intentionally unused.
//
// Empty feed is a valid state (no open roles right now) --
// meta.atsEmpty is set true so verify passes rather than reporting drift.
//
// Public job URLs use https://{slug}.jobs.personio.{tld}/job/{id}. If links
// 404, adjust buildPublicUrl() below and re-verify.

const { safeDiscovered, safeUnitDone } = require('../../progress');
const { sanitizeJobFields } = require('../../jobs');

const PERSONIO_SLUG = '${q(slug)}';
const PERSONIO_TLD = '${q(tld)}';
const PERSONIO_XML_URL = \`https://\${PERSONIO_SLUG}.jobs.personio.\${PERSONIO_TLD}/xml?language=en\`;

function stripHtml(html) {
    if (!html) return '';
    return String(html)
        .replace(/<[^>]+>/g, ' ')
        .replace(/&nbsp;/g, ' ')
        .replace(/&amp;/g, '&')
        .replace(/&lt;/g, '<')
        .replace(/&gt;/g, '>')
        .replace(/&quot;/g, '"')
        .replace(/&#0?39;/g, "'")
        .replace(/&apos;/g, "'")
        .replace(/\\s+/g, ' ')
        .trim();
}

function extractTag(xml, tag) {
    const m = xml.match(new RegExp('<' + tag + '>([\\\\s\\\\S]*?)</' + tag + '>'));
    return m ? m[1] : null;
}

function buildDescription(jobDescriptionsXml) {
    if (!jobDescriptionsXml) return '';
    const parts = [];
    const re = /<jobDescription>([\\s\\S]*?)<\\/jobDescription>/g;
    let m;
    while ((m = re.exec(jobDescriptionsXml)) !== null) {
        const block = m[1];
        const sectionName = stripHtml(extractTag(block, 'name') || '');
        const rawValue = (extractTag(block, 'value') || '').replace(/<!\\[CDATA\\[([\\s\\S]*?)\\]\\]>/g, '$1');
        const plain = stripHtml(rawValue);
        if (plain) parts.push(sectionName ? sectionName + ': ' + plain : plain);
    }
    return parts.join('\\n\\n');
}

function collectOffices(xml) {
    const out = [];
    const re = /<office>([^<]*)<\\/office>/g;
    let m;
    while ((m = re.exec(xml)) !== null) out.push(m[1].trim());
    return out;
}

function buildPublicUrl(id) {
    return 'https://' + PERSONIO_SLUG + '.jobs.personio.' + PERSONIO_TLD + '/job/' + id;
}

function parsePosition(xml) {
    const id = (extractTag(xml, 'id') || '').trim();
    const title = (extractTag(xml, 'name') || '').trim();
    const subcompany = (extractTag(xml, 'subcompany') || '').trim() || null;
    const department = (extractTag(xml, 'department') || '').trim() || null;
    const employmentType = (extractTag(xml, 'employmentType') || '').trim() || null;
    const seniority = (extractTag(xml, 'seniority') || '').trim() || null;
    const schedule = (extractTag(xml, 'schedule') || '').trim() || null;
    const yearsOfExperience = (extractTag(xml, 'yearsOfExperience') || '').trim() || null;
    const keywordsRaw = (extractTag(xml, 'keywords') || '').trim();
    const createdAt = (extractTag(xml, 'createdAt') || '').trim() || null;

    const offices = collectOffices(xml);
    const officePrimary = offices[0] || null;
    const additional = offices.slice(1);
    const looksRemote = additional.concat(officePrimary ? [officePrimary] : []).some((o) => /remote|home.?office/i.test(o));
    const looksHybrid = additional.concat(officePrimary ? [officePrimary] : []).some((o) => /hybrid/i.test(o));
    const attendanceMode = looksRemote ? 'remote' : looksHybrid ? 'hybrid' : 'in-person';

    const jobDescriptionsXml = extractTag(xml, 'jobDescriptions') || '';
    const description = buildDescription(jobDescriptionsXml);

    const skills = keywordsRaw
        ? keywordsRaw.split(',').map((s) => s.trim()).filter(Boolean)
        : [];

    return {
        id,
        title,
        company: subcompany,
        department,
        location: officePrimary,
        additionalOffices: additional,
        employmentType,
        seniority,
        schedule,
        yearsOfExperience,
        attendanceMode,
        description,
        skills,
        createdAt,
        url: id ? buildPublicUrl(id) : null
    };
}

module.exports = {
    // browserless: true tells _orchestrate / verify-source / verify-worker
    // to skip Puppeteer entirely. This extractor uses fetch() only, so
    // launching Chromium is wasted work -- and worse, closeBrowser()
    // can hang 40s+ on an empty page, pinning the worker.
    browserless: true,
    async extract(page, { progress, meta }) {
        meta.pagesVisited++;
        const res = await fetch(PERSONIO_XML_URL, {
            headers: { 'User-Agent': 'Mozilla/5.0', 'Accept': 'application/xml' },
            signal: AbortSignal.timeout(15000)
        });
        if (!res.ok) {
            throw new Error('personio API HTTP ' + res.status);
        }
        const xml = await res.text();

        const blocks = [];
        const re = /<position>([\\s\\S]*?)<\\/position>/g;
        let m;
        while ((m = re.exec(xml)) !== null) blocks.push(m[1]);

        meta.listingHits = blocks.length;
        safeDiscovered(progress, blocks.length);

        if (blocks.length === 0) {
            meta.atsEmpty = true;
            return { items: [], meta };
        }

        const items = [];
        for (const block of blocks) {
            try {
                const p = parsePosition(block);
                if (!p.title) {
                    meta.detailParseFailures++;
                    continue;
                }

                const item = {
                    id: 'personio-${q(slug)}-' + (p.id || p.title),
                    title: p.title,
                    company: p.company,
                    companyUrl: null,
                    companyLogoUrl: null,
                    location: p.location,
                    employmentType: p.employmentType || p.schedule || null,
                    attendanceMode: p.attendanceMode,
                    salary: null,
                    experience: p.yearsOfExperience || null,
                    level: p.seniority || null,
                    openings: null,
                    description: p.description || '',
                    responsibilities: '',
                    requirements: '',
                    skills: p.skills,
                    companyDescription: '',
                    companyLocation: null,
                    companyAddress: null,
                    applicationEndsRaw: null,
                    applicationEndsDate: null,
                    daysLeftAtListTime: null,
                    url: p.url,
                    registrationUrl: p.url,
                    source: '${q(name)}',
                    scrapedAt: Date.now(),
                    publishedAt: p.createdAt || null
                };

                sanitizeJobFields(item);
                if (item.title) items.push(item);
            } catch (e) {
                meta.detailParseFailures++;
                console.warn('  [${q(name)}] personio position parse failed: ' + e.message);
            } finally {
                safeUnitDone(progress);
            }
        }

        return { items, meta };
    }
};
`;
}

module.exports = { renderPersonio };
