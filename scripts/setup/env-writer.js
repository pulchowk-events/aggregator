// scripts/setup/env-writer.js
// Safe .env manipulation for the setup wizard.
//
// Design constraints:
//   - Never destroy a user's existing comments or key order.
//   - Only mutate keys the caller explicitly passes to set().
//   - Always back up .env to .env.bak.<timestamp> before overwriting.
//   - Preserve the raw text of every line that isn't touched.
//
// The setup wizard builds up a large map of { KEY: value } as it walks
// through Discord channel creation, Supabase config, etc. Only at the end
// does it call write() — one atomic write with one backup.

const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..', '..');

class EnvFile {
    constructor(envPath) {
        this.envPath = envPath || path.join(REPO, '.env');
        this.lines = [];        // raw lines, in original order
        this.values = new Map(); // KEY -> value (parsed view)
        this._load();
    }

    _load() {
        if (!fs.existsSync(this.envPath)) {
            this.lines = [
                '# Pulchowk Events Aggregator — environment file',
                '# Generated by scripts/setup/index.js',
                ''
            ];
            return;
        }
        const raw = fs.readFileSync(this.envPath, 'utf8');
        this.lines = raw.split(/\r?\n/);
        for (const line of this.lines) {
            const m = line.match(/^([A-Z_][A-Z0-9_]*)\s*=\s*(.*)$/);
            if (m) this.values.set(m[1], m[2]);
        }
    }

    get(key) {
        return this.values.get(key) || null;
    }

    has(key) {
        return this.values.has(key);
    }

    set(key, value) {
        if (value === null || value === undefined) return;
        const strValue = String(value);
        this.values.set(key, strValue);

        // Find the first line matching this key and update it.
        for (let i = 0; i < this.lines.length; i++) {
            const m = this.lines[i].match(/^([A-Z_][A-Z0-9_]*)\s*=\s*(.*)$/);
            if (m && m[1] === key) {
                this.lines[i] = `${key}=${strValue}`;
                return;
            }
        }

        // Not present — append at the end (with a blank line for readability
        // if the file doesn't already end with one).
        if (this.lines.length > 0 && this.lines[this.lines.length - 1].trim() !== '') {
            this.lines.push('');
        }
        this.lines.push(`${key}=${strValue}`);
    }

    // Set multiple keys from a plain object.
    setAll(obj) {
        for (const [k, v] of Object.entries(obj)) this.set(k, v);
    }

    // Write atomically: back up first, then write.
    write({ backup = true } = {}) {
        let backupPath = null;
        if (backup && fs.existsSync(this.envPath)) {
            backupPath = `${this.envPath}.bak.${Date.now()}`;
            fs.copyFileSync(this.envPath, backupPath);
        }

        // Ensure trailing newline, drop any final empty lines
        const body = this.lines.join('\n').replace(/\n+$/, '') + '\n';
        fs.writeFileSync(this.envPath, body);

        return { path: this.envPath, backupPath, byteSize: Buffer.byteLength(body, 'utf8') };
    }

    // Diff view: what will change if we write()? Useful before asking the
    // user to confirm.
    diff() {
        let existing = [];
        if (fs.existsSync(this.envPath)) {
            existing = fs.readFileSync(this.envPath, 'utf8').split(/\r?\n/);
        }
        const existingValues = new Map();
        for (const line of existing) {
            const m = line.match(/^([A-Z_][A-Z0-9_]*)\s*=\s*(.*)$/);
            if (m) existingValues.set(m[1], m[2]);
        }

        const added = [], updated = [], unchanged = [];
        for (const [k, v] of this.values) {
            if (!existingValues.has(k)) added.push({ key: k, value: v });
            else if (existingValues.get(k) !== v) updated.push({ key: k, from: existingValues.get(k), to: v });
            else unchanged.push({ key: k, value: v });
        }
        return { added, updated, unchanged };
    }
}

// One-shot helper for simple cases.
function writeEnvFile(updates, { envPath = null, backup = true } = {}) {
    const env = new EnvFile(envPath);
    env.setAll(updates);
    return env.write({ backup });
}

module.exports = { EnvFile, writeEnvFile };
